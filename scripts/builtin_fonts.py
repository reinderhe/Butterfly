"""(butterfly) host/ssr_fonts_data.c from Eden's open-source stand-ins for the console's built-in fonts
(src/core/file_sys/system_archive/data/font_*.cpp, yuzu Emulator Project, GPL-2.0-or-later): plain TrueType data, in the
order of nn::pl's font types. Usage: python scripts/builtin_fonts.py <Eden's system_archive/data folder>"""
import os, re, sys

TYPES = ["standard", "chinese_simplified", "extended_chinese_simplified", "chinese_traditional", "korean", "nintendo_extended"]


def font_bytes(path):
    text = open(path, encoding="utf-8").read()
    body = text[text.index("{{") + 2:text.rindex("}}")]
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{1,2})", body))


def c_string(data):
    out, line = [], []
    for b in data:
        line.append("\\%03o" % b if b < 32 or b > 126 or b in (34, 92, 63) else chr(b))
        if len(line) >= 120:
            out.append('    "%s"' % "".join(line))
            line = []
    if line:
        out.append('    "%s"' % "".join(line))
    return "\n".join(out)


def main():
    src = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    parts = ["/* Generated by scripts/builtin_fonts.py: the console's built-in fonts as Eden's open-source stand-ins",
             "   (yuzu Emulator Project, GPL-2.0-or-later). Do not edit. */",
             "#include <stddef.h>", ""]
    for t in TYPES:
        data = font_bytes(os.path.join(src, "font_%s.cpp" % t))
        s = c_string(data)   # (three-digit octal escapes: a digit after one cannot run on into it)
        parts += ["static const char font_%s[] =" % t, s + ";", ""]
        print(t, len(data), "bytes")
    parts.append("const unsigned char *const ssr_builtin_fonts[6] = {%s};" %
                 ", ".join("(const unsigned char *)font_%s" % t for t in TYPES))
    parts.append("const size_t ssr_builtin_font_sizes[6] = {%s};" % ", ".join("sizeof font_%s - 1" % t for t in TYPES))
    open(os.path.join(here, "..", "host", "ssr_fonts_data.c"), "w", encoding="utf-8").write("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
